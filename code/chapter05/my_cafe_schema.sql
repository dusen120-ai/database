-- Chapter 05. 개인 서비스(내 카페 방문 기록) DDL 초안
-- 시작 상태: public.cafes, menu_items, visits, visit_items가 존재하지 않음
-- 완료 상태: 네 테이블이 생성되고 데이터는 비어 있음
-- 미확정 정책(폐업 처리, 카페별 메뉴, 같은 날 재방문, 평점 범위)은 제약으로 만들지 않습니다.

BEGIN;

-- 카페 한 행 = 카페 한 곳 (P05-R01, R02)
CREATE TABLE public.cafes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    address VARCHAR(200),
    naver_place_id VARCHAR(50) UNIQUE,
    my_rating NUMERIC(2,1)
);

-- 메뉴 한 행 = 메뉴 종류 한 개 (P05-R05)
-- 카페별 메뉴인지 미확정(P05-Q02)이므로 cafe_id를 두지 않습니다.
CREATE TABLE public.menu_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    category VARCHAR(20) NOT NULL
);

-- 방문 한 행 = 특정 카페를 방문한 사건 한 번 (P05-R03, R04)
-- 같은 날 재방문 여부가 미확정(P05-Q03)이므로 UNIQUE(cafe_id, visited_on)를 두지 않습니다.
CREATE TABLE public.visits (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cafe_id INTEGER NOT NULL REFERENCES public.cafes(id),
    visited_on DATE NOT NULL,
    rating NUMERIC(2,1),
    comment VARCHAR(200)
);

-- 주문 메뉴 한 행 = 한 방문에서 주문한 메뉴 한 개 (P05-R06, R07, R08)
-- visits N:M menu_items를 푸는 연결(사건) 테이블입니다.
CREATE TABLE public.visit_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id INTEGER NOT NULL REFERENCES public.visits(id),
    menu_item_id INTEGER NOT NULL REFERENCES public.menu_items(id),
    price INTEGER,
    memo VARCHAR(200)
);

COMMIT;

SELECT
    to_regclass('public.cafes') AS cafes_table,
    to_regclass('public.menu_items') AS menu_items_table,
    to_regclass('public.visits') AS visits_table,
    to_regclass('public.visit_items') AS visit_items_table;
