-- Chapter 07. 개인 프로젝트(내 카페 방문 기록) 중간 프로젝트 초안 스키마
-- 목적: Chapter 07 답안 12-3 ERD를 DBeaver Diagram으로 그리기 위한 구조 생성
-- 시작 상태: cafe_project 스키마가 존재하지 않음
-- 완료 상태: cafe_project 스키마·네 테이블·제약조건 생성, 네 테이블 0행
-- Chapter 05~06의 public.cafes 등 기존 테이블은 건드리지 않습니다.

SELECT current_database();
SELECT current_user;

BEGIN;

DO $$
BEGIN
    IF current_database() <> 'ai_database_book' THEN
        RAISE EXCEPTION '생성 중단: 현재 데이터베이스는 %입니다.', current_database();
    END IF;

    IF to_regnamespace('cafe_project') IS NOT NULL THEN
        RAISE EXCEPTION '생성 중단: cafe_project 스키마가 이미 존재합니다.';
    END IF;
END
$$;

CREATE SCHEMA cafe_project;

-- 카페 한 곳 (P07-MR01·MR02·MR09, P07-MD03)
CREATE TABLE cafe_project.cafes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    address VARCHAR(200),
    naver_place_id VARCHAR(50),
    my_rating NUMERIC(2, 1),
    closed_on DATE,

    CONSTRAINT uq_cafes_naver_place_id
        UNIQUE (naver_place_id),

    CONSTRAINT chk_cafes_name_not_blank
        CHECK (btrim(name) <> ''),

    CONSTRAINT chk_cafes_my_rating
        CHECK (my_rating BETWEEN 1 AND 5)
);

-- 한 카페가 파는 메뉴 한 개 (P07-MR03, P07-MD01)
CREATE TABLE cafe_project.menu_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cafe_id INTEGER NOT NULL,
    name VARCHAR(100) NOT NULL,
    category VARCHAR(20) NOT NULL,

    CONSTRAINT fk_menu_items_cafe
        FOREIGN KEY (cafe_id)
        REFERENCES cafe_project.cafes(id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_menu_items_cafe_name
        UNIQUE (cafe_id, name),

    CONSTRAINT chk_menu_items_name_not_blank
        CHECK (btrim(name) <> ''),

    CONSTRAINT chk_menu_items_category
        CHECK (category IN ('음료', '디저트'))
);

-- 카페를 방문한 사건 한 번 (P07-MR04·MR05·MR08, P07-MD02)
CREATE TABLE cafe_project.visits (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cafe_id INTEGER NOT NULL,
    visited_on DATE NOT NULL,
    rating NUMERIC(2, 1),
    comment VARCHAR(200),

    CONSTRAINT fk_visits_cafe
        FOREIGN KEY (cafe_id)
        REFERENCES cafe_project.cafes(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_visits_rating
        CHECK (rating BETWEEN 1 AND 5)
);

-- 한 방문에서 주문한 메뉴 한 개 (P07-MR06·MR07·MR10, P07-MD04)
CREATE TABLE cafe_project.visit_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id INTEGER NOT NULL,
    menu_item_id INTEGER NOT NULL,
    price INTEGER,
    memo VARCHAR(200),

    CONSTRAINT fk_visit_items_visit
        FOREIGN KEY (visit_id)
        REFERENCES cafe_project.visits(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_visit_items_menu_item
        FOREIGN KEY (menu_item_id)
        REFERENCES cafe_project.menu_items(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_visit_items_price
        CHECK (price IS NULL OR price >= 0)
);

COMMIT;

SELECT conrelid::regclass AS table_name, conname AS constraint_name, contype AS constraint_type
FROM pg_constraint
WHERE connamespace = 'cafe_project'::regnamespace
  AND contype IN ('u', 'f', 'c')
ORDER BY 1, 2;

